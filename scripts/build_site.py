def inject_nav(p: Path, up="../"):
    s = p.read_text(encoding="utf-8")
    if 'id="fsb-nav"' not in s:
        m = re.search(r"<body[^>]*>", s)
        s = s[:m.end()] + "\n" + NAV.format(up=up) + s[m.end():]
    p.write_text(s, encoding="utf-8")


def split_bundle(vdir: Path):
    b = vdir / "data" / "bundle.js"
    t = b.read_text(encoding="utf-8")
    docs = json.loads(t[t.index("window.FSB_DATASETS = ") + len("window.FSB_DATASETS = "):].rstrip().rstrip(";"))
    for f in (vdir / "data").glob("*"):
        f.unlink()
    idx = []
    for d in docs:
        (vdir / "data" / f"ds_{d['name']}.js").write_text(
            "(window.FSB_DS_LOADED=window.FSB_DS_LOADED||{})[" + json.dumps(d["name"]) + "]="
            + json.dumps(d, separators=(",", ":")) + ";\n", encoding="utf-8")
        idx.append({"name": d["name"], "illustrative": d.get("illustrative", False)})
    (vdir / "data" / "index.js").write_text("// generated by scripts/build_site.py\nwindow.FSB_DATASET_INDEX="
                                            + json.dumps(idx) + ";\n", encoding="utf-8")
    ih = vdir / "index.html"
    ih.write_text(ih.read_text(encoding="utf-8").replace('<script src="data/bundle.js"></script>',
                                                         '<script src="data/index.js"></script>'), encoding="utf-8")
    return [d["name"] for d in docs]



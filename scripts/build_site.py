"""Build the static GitHub Pages site into site/ from demos/ (no manual copying).

    python scripts/build_site.py            # -> site/
Relative paths only, so it works at https://nisaral.github.io/falsesafe-bench/ and offline.
The viewer3d bundle is split into per-dataset files (data/ds_<name>.js) loaded on demand.
"""
from __future__ import annotations
import html, json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEMOS, OUT = ROOT / "demos", ROOT / "site"
REPO = "https://github.com/nisaral/falsesafe-bench"
PR = REPO + "/pull/1"
OLD = [("scientific_viewer", "Scientific viewer (k-sweep, illustrative contours)"),
       ("watch_safety_go_wrong", "Watch safety go wrong (toy)"),
       ("studio", "Studio (toy shield simulation)"),
       ("one_robot_learns_to_be_safe", "One robot learns to be safe (story)")]
NAV = ('<nav id="fsb-nav" style="position:fixed;left:8px;bottom:8px;z-index:10000;display:flex;gap:12px;align-items:center;'
       'background:rgba(13,17,23,.92);border:1px solid #30363d;border-radius:8px;padding:5px 10px;font:12px system-ui">'
       '<a href="{up}index.html" style="color:#e6edf3;font-weight:700;text-decoration:none">FalseSafe-Bench</a>'
       '<a href="{up}viewer3d/index.html" style="color:#58a6ff">3D viewer</a>'
       '<a href="{up}gym/index.html" style="color:#58a6ff">Interactive gym</a>'
       '<a href="{up}index.html#illustrative" style="color:#d29922">Illustrative demos</a>'
       '<a href="' + REPO + '" style="color:#8b949e">GitHub</a></nav>')


def inject_nav(p: Path, up="../"):
    s = p.read_text(encoding="utf-8")
    if 'id="fsb-nav"' not in s:
        m = re.search(r"<body[^>]*>", s)
        s = s[:m.end()] + "\n" + NAV.format(up=up) + s[m.end():]
    p.write_text(s, encoding="utf-8")


def split_bundle(vdir: Path):
    b = vdir / "data" / "bundle.js"
    t = b.read_text(encoding="utf-8")
    docs = json.loads(t[t.index("window.FSB_DATASETS = ") + len("window.FSB_DATASETS = "):].rstrip().rstrip(";"))
    for f in (vdir / "data").glob("*"):
        f.unlink()
    idx = []
    for d in docs:
        (vdir / "data" / f"ds_{d['name']}.js").write_text(
            "(window.FSB_DS_LOADED=window.FSB_DS_LOADED||{})[" + json.dumps(d["name"]) + "]="
            + json.dumps(d, separators=(",", ":")) + ";\n", encoding="utf-8")
        idx.append({"name": d["name"], "illustrative": d.get("illustrative", False)})
    (vdir / "data" / "index.js").write_text("// generated by scripts/build_site.py\nwindow.FSB_DATASET_INDEX="
                                            + json.dumps(idx) + ";\n", encoding="utf-8")
    ih = vdir / "index.html"
    ih.write_text(ih.read_text(encoding="utf-8").replace('<script src="data/bundle.js"></script>',
                                                         '<script src="data/index.js"></script>'), encoding="utf-8")
    return [d["name"] for d in docs]



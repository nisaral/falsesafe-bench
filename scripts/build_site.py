def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    shutil.copytree(DEMOS / "common", OUT / "common")
    for n in ["viewer3d", "gym"] + [n for n, _ in OLD]:
        shutil.copytree(DEMOS / n, OUT / n, ignore=shutil.ignore_patterns("*.json", "README.md") if n == "viewer3d" else shutil.ignore_patterns("README.md"))
    if (DEMOS / "scientific_viewer" / "data.json").exists():
        shutil.copy(DEMOS / "scientific_viewer" / "data.json", OUT / "scientific_viewer" / "data.json")
    names = split_bundle(OUT / "viewer3d")
    for n in ["viewer3d", "gym"] + [n for n, _ in OLD]:
        inject_nav(OUT / n / "index.html")
    (OUT / "glossary.html").write_text(GLOSSARY, encoding="utf-8")
    for img in ["og.png", "viewer3d.png"] + [f"shot_{n}.png" for n, _ in OLD]:
        src = ROOT / "docs" / "img" / img
        if src.exists():
            shutil.copy(src, OUT / img)
    (OUT / "index.html").write_text(landing(names), encoding="utf-8")
    (OUT / ".nojekyll").write_text("")
    (OUT / "404.html").write_text('<!doctype html><meta charset="utf-8"><title>Not found</title><p>Not found. <a href="./">FalseSafe-Bench home</a></p>')
    tot = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"site/ built: {sum(1 for f in OUT.rglob('*') if f.is_file())} files, {tot/1e6:.1f} MB; datasets: {names}")


if __name__ == "__main__":
    main()
